def _binary(prompt, left, right):
    return {
        "question_text": prompt,
        "options": [left, right],
    }


def _ternary(prompt, a, b, c):
    return {
        "question_text": prompt,
        "options": [a, b, c],
    }


def _open_choice(prompt, *options):
    return {
        "question_text": prompt,
        "options": list(options),
    }


