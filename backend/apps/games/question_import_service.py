import json
import re
from pathlib import Path
from typing import Any

from django.db import transaction
from django.db.models import Max

from .models import Game, GameCategory, GameOption, GameQuestion

_CATEGORY_SLUG_PATTERN = re.compile(r"[a-z0-9_-]+")


def load_rows_from_json_path(file_path: Path) -> list[dict]:
    with file_path.open("r", encoding="utf-8") as handle:
        payload = json.load(handle)
    return _normalize_payload(payload)


def load_rows_from_uploaded_json(uploaded_file) -> list[dict]:
    raw = uploaded_file.read()
    if isinstance(raw, bytes):
        text = raw.decode("utf-8-sig")
    else:
        text = str(raw)
    payload = json.loads(text)
    return _normalize_payload(payload)


def import_game_questions_rows(
    rows: list[dict],
    *,
    game_name: str = "Imported Questions",
    game_type: str = Game.Type.CHOICE,
    dry_run: bool = False,
) -> dict[str, Any]:
    game, _ = Game.objects.get_or_create(
        name=game_name,
        defaults={
            "type": game_type,
            "description": "Autogenerated game for imported questions.",
            "is_active": True,
        },
    )

    total_processed = len(rows)
    created = 0
    skipped = 0
    errors = 0
    error_details: list[str] = []

    next_order = (
        GameQuestion.objects.filter(game=game).aggregate(max_order=Max("order")).get("max_order") or 0
    ) + 1

    for index, item in enumerate(rows, start=1):
        try:
            if not isinstance(item, dict):
                raise ValueError("row must be an object")

            raw_category = str(item.get("category", "")).strip().lower()
            category_slug = raw_category.replace(" ", "-")
            if not category_slug:
                raise ValueError("category is required")
            if not _CATEGORY_SLUG_PATTERN.fullmatch(category_slug):
                raise ValueError(
                    "category slug can contain only lowercase letters, numbers, '_' and '-'"
                )

            question_text = str(item.get("question_text", "")).strip()
            if not question_text:
                raise ValueError("question_text is required")

            question_game_type = str(item.get("game_type", "")).strip()
            valid_game_types = {choice for choice, _ in GameQuestion.GameType.choices}
            if question_game_type not in valid_game_types:
                raise ValueError(
                    f"invalid game_type '{question_game_type}'. "
                    f"Valid: {', '.join(sorted(valid_game_types))}"
                )

            raw_options = item.get("options")
            if not isinstance(raw_options, list):
                raise ValueError("options must be a list")

            category_name = str(item.get("category_name", "")).strip()
            if not category_name:
                category_name = category_slug.replace("_", " ").replace("-", " ").title()

            category, _ = GameCategory.objects.get_or_create(
                slug=category_slug,
                defaults={
                    "name": category_name,
                    "emoji": str(item.get("emoji", "")).strip(),
                    "description": "",
                    "is_active": True,
                },
            )

            duplicate_exists = GameQuestion.objects.filter(
                category=category,
                question_text__iexact=question_text,
            ).exists()
            if duplicate_exists:
                skipped += 1
                continue

            if raw_options and not all(isinstance(opt, dict) for opt in raw_options):
                raise ValueError("each option must be an object, e.g. {'text': 'Coffee ☕'}")

            normalized_options: list[dict[str, Any]] = []
            for option_index, option in enumerate(raw_options, start=1):
                option_text = str(option.get("text", "")).strip()
                if not option_text:
                    raise ValueError(f"option {option_index} is missing text")
                normalized_options.append({"text": option_text})

            trait_mapping = item.get("trait_mapping")
            if trait_mapping is None:
                trait_mapping = {}
            if not isinstance(trait_mapping, dict):
                raise ValueError("trait_mapping must be an object if provided")

            tags = item.get("tags")
            if tags is None:
                tags = []
            if not isinstance(tags, list):
                raise ValueError("tags must be a list if provided")

            difficulty = item.get("difficulty", 1)
            try:
                difficulty = int(difficulty)
            except (TypeError, ValueError) as exc:
                raise ValueError("difficulty must be an integer") from exc
            if difficulty < 1:
                raise ValueError("difficulty must be >= 1")

            if dry_run:
                created += 1
                continue

            with transaction.atomic():
                question = GameQuestion.objects.create(
                    game=game,
                    category=category,
                    game_type=question_game_type,
                    question_text=question_text,
                    options=normalized_options,
                    trait_mapping=trait_mapping,
                    tags=tags,
                    difficulty=difficulty,
                    order=next_order,
                    is_active=_parse_bool(item.get("is_active", True)),
                )
                if normalized_options:
                    GameOption.objects.bulk_create(
                        [
                            GameOption(
                                question=question,
                                option_text=option["text"],
                                order=option_index,
                            )
                            for option_index, option in enumerate(normalized_options, start=1)
                        ]
                    )
                next_order += 1

            created += 1
        except Exception as exc:  # noqa: BLE001
            errors += 1
            error_details.append(f"row {index}: {exc}")
            continue

    return {
        "game_id": game.id,
        "game_name": game.name,
        "total_processed": total_processed,
        "created": created,
        "skipped": skipped,
        "errors": errors,
        "error_details": error_details,
    }


def _normalize_payload(payload: Any) -> list[dict]:
    if isinstance(payload, dict):
        payload = payload.get("questions")
    if not isinstance(payload, list):
        raise ValueError("JSON must be a list of question objects.")
    return payload


def _parse_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    normalized = str(value).strip().lower()
    return normalized in {"1", "true", "yes", "y", "on"}
