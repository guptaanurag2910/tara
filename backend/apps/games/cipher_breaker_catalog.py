def caesar_encrypt(phrase: str, shift: int = 3) -> str:
    """Shift letters while preserving spaces and punctuation."""
    result = []
    for char in phrase.upper():
        if "A" <= char <= "Z":
            result.append(chr((ord(char) - ord("A") + shift) % 26 + ord("A")))
        else:
            result.append(char)
    return "".join(result)
